    private void loadSnippets() {
        String filter = (String) cmbFilterLanguage.getSelectedItem();
        String searchText = txtSearch.getText().trim().toLowerCase();

        if (filter == null || filter.equals("All")) {
            currentSnippets = dbHelper.getAllSnippets();
        } else {
            currentSnippets = dbHelper.getSnippetsByLanguage(filter);
        }

        if (!searchText.isEmpty()) {
            List<Snippet> matches = new ArrayList<>();
            for (Snippet s : currentSnippets) {
                if (s.getTitle().toLowerCase().contains(searchText)) {
                    matches.add(s);
                }
            }
            currentSnippets = matches;
        }

        SnippetTableModel model = (SnippetTableModel) snippetTable.getModel();
        model.setRowCount(0);
        for (Snippet s : currentSnippets) {
            model.addRow(new Object[]{s.getTitle(), s.getLanguage(), s.getDateCreated()});
        }

        if (currentSnippets.isEmpty()) {
            boolean noFilterActive = searchText.isEmpty() && (filter == null || filter.equals("All"));
            emptyStateLabel.setText(noFilterActive
                    ? "No snippets yet \u2014 click \"Add New Snippet\" to get started."
                    : "No snippets match your search or filter.");
            jScrollPane1.setViewportView(emptyStatePanel);
        } else {
            jScrollPane1.setViewportView(snippetTable);
        }
    }

