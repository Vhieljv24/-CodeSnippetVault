    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = snippetTable.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a snippet to edit.");
            return;
        }
        Snippet selected = currentSnippets.get(row);
        SnippetFormDialog dialog = new SnippetFormDialog(this, selected);
        dialog.setVisible(true);
        if (dialog.wasSaved()) {
            loadSnippets();
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = snippetTable.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a snippet to delete.");
            return;
        }
        Snippet selected = currentSnippets.get(row);
        int confirm = JOptionPane.showConfirmDialog(this,
                "Delete \"" + selected.getTitle() + "\"?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            dbHelper.deleteSnippet(selected.getId());
            loadSnippets();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

