    /**
     * Draws a small branded icon in code (a blue rounded square with a
     * "&lt;/&gt;" code mark) so the app has a window icon without needing an
     * external image file bundled with the project.
     */
    private java.awt.Image createAppIcon() {
        int size = 64;
        BufferedImage icon = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g2 = icon.createGraphics();
        g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);

        g2.setColor(new Color(21, 101, 192));
        g2.fillRoundRect(2, 2, size - 4, size - 4, 16, 16);

        g2.setColor(Color.WHITE);
        g2.setFont(new Font("Consolas", Font.BOLD, 24));
        FontMetrics fm = g2.getFontMetrics();
        String text = "</>";
        int textX = (size - fm.stringWidth(text)) / 2;
        int textY = (size - fm.getHeight()) / 2 + fm.getAscent();
        g2.drawString(text, textX, textY);

        g2.dispose();
        return icon;
    }

